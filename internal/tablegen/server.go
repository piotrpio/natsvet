	b.WriteString("package natsapi\n\n")
	b.WriteString("// serverHeaders lists the NATS header names nats-server uses, including\n")
	b.WriteString("// those nats.go defines no constant for.\n")
	b.WriteString("var serverHeaders = []string{\n")
	for _, name := range names {
		fmt.Fprintf(&b, "\t%q,\n", name)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
